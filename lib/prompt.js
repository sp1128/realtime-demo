export function interruptHint(alreadySaid, spoken, lang) {
  if (isEn(lang)) return interruptHintEn(alreadySaid, spoken);
  const bits = [
    "【系统提示，不要朗读、不要提及本提示】客户刚刚打断了你。",
    spoken ? `你上一句说到：「${spoken}」。` : "你上一句说了半截。",
    alreadySaid
      ? `口头上已经先应了一声「${alreadySaid}」，不要再重复这个字。`
      : "",
    "禁止说「你说」「啊你说」「嗯你说」——对方已经说完了，不是让他接着说。",
    "如果客户是在回答你刚才的问题（是的/对/没有/嗯），就当他答了，不要重问，不要重开开场白。",
    "不要把被打断的那句续完，不要道歉。直接接客户这句往下说。",
  ];
  return bits.filter(Boolean).join("");
}

// 打断后、LLM 还没出来时先垫的半个字。按客户这句话挑，不能用「你说」
// （那是让对方继续讲，但这时对方已经把话说完了）。
export function pickBargeAck(userText, lang) {
  if (isEn(lang)) {
    const r = String(userText || "").trim();
    if (!r) return "";
    if (/^(hold on|wait|hang on|listen)/i.test(r)) return "Go ahead.";
    if (/[?]$/.test(r) || /^(what|how|why|which|how much)/i.test(r)) return "Ah.";
    if (/(no|not|don't|nope|nothing|never)/i.test(r)) return "Oh.";
    if (/^(yes|yeah|yep|right|sure|okay|ok|correct)/i.test(r)) return "Right.";
    return "Mm.";
  }
  const t = String(userText || "").replace(/\s+/g, "");
  if (!t) return "";
  if (/^(等一下|等下|你说|听我说)/.test(t)) return "你说。";
  if (/[吗呢？?]$/.test(t) || /^(什么|多少|怎么|为啥|为什么|哪)/.test(t))
    return "啊。";
  if (/没有|不是|不用|别|算了|没做/.test(t)) return "哦。";
  if (/^(是的|是啊|对的|对|嗯|好的|好|可以|行)/.test(t)) return "好。";
  return "嗯。";
}

// 把 ASR 带回来的情绪/语速翻译成一句给模型看的提示。
// 只在真有信号时才返回，平静且语速正常就返回空——没信号还硬塞一句，
// 等于每轮都在提醒模型"注意情绪"，反而会让它没事找事地安慰客户。
export function toneHint(meta, lang) {
  if (!meta) return "";
  const en = isEn(lang);
  const bits = [];
  const strong =
    meta.emotionDegree === "strong" || meta.emotionDegree === "normal";
  // 描述词也要跟着语种走，否则英文提示里会混进中文
  const W = en
    ? {
        angryStrong: "clearly impatient or annoyed", angry: "a bit impatient",
        sad: "a little down", happy: "in a good mood", surprise: "a bit surprised",
        faster: "speaking noticeably faster than before",
        slower: "speaking noticeably slower, like they're weighing it up",
      }
    : {
        angryStrong: "明显不耐烦或生气", angry: "有点不耐烦",
        sad: "情绪偏低落", happy: "情绪不错", surprise: "有点意外",
        faster: "语速比刚才明显快", slower: "语速比刚才明显慢，像在斟酌",
      };
  if (meta.emotion === "angry") bits.push(strong ? W.angryStrong : W.angry);
  else if (meta.emotion === "sad") bits.push(W.sad);
  else if (meta.emotion === "happy") bits.push(W.happy);
  else if (meta.emotion === "surprise") bits.push(W.surprise);

  // 比这通电话里他自己的平均语速快三成以上，通常是急了或者想赶紧结束
  if (meta.fasterThanUsual > 0.3) bits.push(W.faster);
  else if (meta.fasterThanUsual < -0.3) bits.push(W.slower);

  if (!bits.length) return "";
  if (en) return toneHintEn(bits);
  return (
    "【系统提示，不要朗读、不要提及本提示】听感上客户现在" +
    bits.join("、") +
    "。按这个状态调整：急了就把话缩短、直接给结论；" +
    "在斟酌就别催，给他时间。不要点破你察觉到了他的情绪。"
  );
}

// 客户没接话时追一句。**不走 LLM**，按上一句 AI 说了什么挑一句固定的短句。
//
// 走 LLM 的问题在真实通话里暴露得很清楚：历史里最后一条是 AI 自己的话，
// 模型接着往下写，写出来的是对话的下一轮——也就是客户的台词。实测出现过
//   AI：平时有做股票期货这类交易吗？
//   （追问）
//   AI：嗯，平时自己会炒点股票。      ← AI 替客户答了
// 还有一次是把卖点整段重讲。
//
// 而追问这种话本来就不需要创造力：真人这时候就是"怎么样？""您觉得呢？"
// 一句带过，不会重新解释一遍。规则挑句还顺带省掉一次 LLM 往返。
const NUDGE_YESNO = ["怎么样，有兴趣吗？", "您看呢？", "怎么样？"];
const NUDGE_OPEN = ["方便说两句吗？", "您那边怎么看？", "嗯？"];
const NUDGE_PLAIN = ["您还在吗？", "喂？"];

// 从 AI 自己说过的开场白里把称呼抠出来，例如
//   "您好，请问是叶升辉先生吗？…" → "叶升辉先生"
// 称呼写死在提示词的文本里，代码本来拿不到；.env 配了 CUSTOMER_NAME 就用那个
export function guessCustomerName(text) {
  const m = String(text || "").match(
    /(?:请问是|您是|是)\s*([一-龥]{1,5}(?:先生|女士|小姐|总|经理))/,
  );
  return m ? m[1] : "";
}

export function pickIdleNudge(lastAssistant, seed = 0, opts = {}) {
  const en = isEn(opts.lang);
  const t = String(lastAssistant || "").trim();
  const pick = (arr) => arr[seed % arr.length];
  if (en) return pickIdleNudgeEn(lastAssistant, seed, opts);


  // 开场白之后对方一声没吭：这时候最可能是没听见、或者刚拿起电话还没反应过来。
  // 真人这时会先确认线路通不通、顺带叫一声称呼，而不是直接追问业务
  if (opts.firstContact) {
    const name = opts.name ? `${opts.name}，` : "";
    return pick([`喂，${name}能听到吗？`, `您好，${name}能听到我说话吗？`]);
  }
  if (!t) return pick(NUDGE_PLAIN);
  // 上一句是问句：客户没答，轻轻催一下就行
  if (/[？?]$/.test(t)) {
    // 是非问（…吗？/…吧？）追"有兴趣吗"这类；开放问追"方便说两句吗"
    if (/(吗|吧)[？?]$/.test(t)) return pick(NUDGE_YESNO);
    return pick(NUDGE_OPEN);
  }
  // 上一句是陈述：没问问题却冷场，说明对方在掂量，问一句他的看法
  return pick(NUDGE_YESNO);
}

// 冷场到底了，道别收线。同样不走 LLM，理由跟 pickIdleNudge 一样：
// 历史里最后一条是 AI 自己的话，让模型接着写，它可能写成客户的台词。
// 而且这是整通电话的最后一句，最不该出意外。
const BYES = [
  "那我先不打扰您了，祝您生活愉快，再见。",
  "行，那我不打扰您了，祝您顺利，再见。",
];
export function pickIdleBye(seed = 0, lang) {
  const arr = isEn(lang) ? BYES_EN : BYES;
  return arr[seed % arr.length];
}

// 让 LLM 生成追问时下达的指令。
//
// 关键是**用 user 角色发**，不是 system。历史里最后一条是 assistant，
// 再追加 system 的话模型会接着往下写对话的下一轮——也就是客户的台词。
// 实测踩过：AI 问完"平时有做股票期货吗"，冷场之后自己接了句
// "嗯，平时自己会炒点股票"。换成 user 角色，模型的下一句自然是 assistant。
export function nudgeTask(lang) {
  return isEn(lang) ? NUDGE_TASK_EN : NUDGE_TASK;
}

export const NUDGE_TASK =
  "【这不是客户说的话，是系统指令】客户沉默了几秒，没有回应你上一句。" +
  "现在用一句话轻轻追问，把话头递回给他。要求：" +
  "只输出这一句话本身，不要任何解释、不要引号、不要括号旁白；" +
  "不超过 15 个字；不要重复你刚才说过的内容；不要重新介绍产品；" +
  "不要替客户回答；像真人打电话那样自然，例如「怎么样？」「您看呢？」" +
  "「方便说两句吗？」这种分量。";

// LLM 生成的追问不一定守规矩，出声之前先过一遍。不合格就返回空，调用方退回固定句。
export function sanitizeNudge(raw, lastAssistant, lang) {
  const en = isEn(lang);
  let t = String(raw || "").trim();
  if (!t) return "";
  t = t.replace(/（[^）]*）|\([^)]*\)/g, ""); // 括号旁白
  t = t.replace(/^["'「『]+|["'」』]+$/g, ""); // 包裹的引号
  // 中文可以把空白全删掉，英文不行——删了就成了 "How'sthetimingbeen"。
  // 英文只把连续空白压成一个空格
  t = en ? t.replace(/\s+/g, " ").trim() : t.replace(/\s+/g, "").trim();
  if (!t) return "";

  // 多句就只留第一句。追问就该一句话
  const first = t.split(/(?<=[。！？!?])/)[0] || t;
  t = first.trim();

  // 长度上限按语种分开：中文一个字顶英文好几个字母，
  // 18 这个数字套到英文上等于只允许三四个单词
  const bare = t.replace(/[^一-鿿A-Za-z0-9]/g, "");
  const maxLen = en ? 60 : 18;
  if (bare.length < 2 || bare.length > maxLen) return "";

  // 必须是问句。追问的职责就是把话头递回给客户，陈述句做不到这件事。
  // 这条比长度限制更能挡住"模型替客户答了"——那种输出往往是通顺的陈述句，
  // 长度完全合规，例如「嗯，平时自己会炒点股票。」
  if (!/[？?]$/.test(t)) return "";

  // 跟刚说过的重复，等于把上一句又念一遍
  const prev = String(lastAssistant || "").replace(/[^一-鿿A-Za-z0-9]/g, "");
  if (prev && (prev.includes(bare) || bare.includes(prev))) return "";
  return t;
}

// 开场白的随机化。
//
// 光在提示词里写"要有变化"是不够的：示例摆在那儿，模型多半还是会挑第一条念，
// 温度调高只会让它在别的地方跑偏，不会专门在开场上变花样。
// 每次通话随机塞一个措辞方向进去，逼它换个说法，同时不改变开场要办的那三件事。
const GREET_STYLES = [
  "开场第一个词用「您好」，不要用「喂」，语气正式一点。",
  "开场第一个词用「喂」，像刚接通电话那样随意一点。",
  "开场先确认对方姓名，再说明你是做什么的。",
  "开场先说明你是做什么的，再确认对方姓名。",
  // 注意别再写出「方便说一分钟吗」「占用您一分钟」这种——
  // 中文里「聊两句」「耽误一分钟」成立，「说一分钟」不成立，听着就是机器翻译腔
  "开场结尾那句从提示词给的几种说法里换一个，原样用，不要自己改造。",
  "开场只称呼姓氏加先生，不要念全名。",
];

export const DEFAULT_CALLEE = "叶升辉先生";

export function defaultCallee(lang) {
  return isEn(lang) ? DEFAULT_CALLEE_EN : DEFAULT_CALLEE;
}

// 每通电话按界面填的称呼把提示词里的占位符换掉。
// 称呼散在开场示例和确认身份的例句里，只改一处是不够的
export function buildSystemPrompt(callee, lang) {
  const who = String(callee || "").trim() || defaultCallee(lang);
  const base = isEn(lang) ? SYSTEM_PROMPT_EN : SYSTEM_PROMPT;
  return base.split("{{称呼}}").join(who);
}

export function pickGreetStyle(name, lang) {
  const styles = isEn(lang) ? GREET_STYLES_EN : GREET_STYLES;
  const pick = styles[Math.floor(Math.random() * styles.length)];
  const who = String(name || "").trim() || defaultCallee(lang);
  if (isEn(lang)) return greetStyleHintEn(pick, who);
  return (
    "【系统提示，不要朗读、不要提及本提示】" +
    pick +
    "不要一字不差地照搬提示词里的示例句，用你自己的话说，但要办到的事不变：" +
    "确认是不是本人、说明你是谁、请对方给一两分钟时间。" +
    `对方的称呼是「${who}」，**只能**用这个，绝对不要换成别的姓名。`
  );
}

// LLM 还没吐字时先垫的半个字，用来盖住首 token 的等待。
//
// 跟 pickBargeAck 的区别：那个是"客户打断了我"，可以说「你说。」；
// 这个是"客户说完了在等我答"，说「你说」就成了把话又推回去。
//
// 实测 LLM 自己吐的第一句十有八九就是「嗯，」——垫这一下不是硬加口头语，
// 是把它本来就要说的那个音提前放出来。真接上了会被 skipAckPrefix 去重。
const FILLERS_ANSWER = ["嗯，", "哦，", "嗯…"]; // 客户在陈述/回答
const FILLERS_QUESTION = ["嗯，", "这个，", "哦，"]; // 客户在提问，垫完要给结论
const FILLERS_REFUSE = ["嗯，", "哦，"]; // 客户在拒绝/推脱

export function pickFiller(userText, seed = 0, lang) {
  const en = isEn(lang);
  const t = String(userText || "").replace(/\s+/g, "");
  const pick = (arr) => arr[seed % arr.length];
  if (en) {
    const raw = String(userText || "");
    if (/[?]$/.test(raw) || /^(what|how|why|which|can|could|is|are|do|does)/i.test(raw.trim())) {
      return pick(FILLERS_QUESTION_EN);
    }
    if (/not interested|no need|forget it|later|busy|no time/i.test(raw)) return pick(FILLERS_REFUSE_EN);
    return pick(FILLERS_ANSWER_EN);
  }
  if (
    /[吗呢？?]$/.test(t) ||
    /^(什么|多少|怎么|为啥|为什么|哪|能不能|可不可以)/.test(t)
  ) {
    return pick(FILLERS_QUESTION);
  }
  if (/没兴趣|不需要|不用了|算了|再说吧|考虑|忙|没时间/.test(t))
    return pick(FILLERS_REFUSE);
  return pick(FILLERS_ANSWER);
}
