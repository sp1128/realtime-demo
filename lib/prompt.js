export function interruptHint(alreadySaid, spoken) {
  const bits = [
    "【系统提示，不要朗读、不要提及本提示】客户刚刚打断了你。",
    spoken ? `你上一句说到：「${spoken}」。` : "你上一句说了半截。",
    alreadySaid ? `口头上已经先应了一声「${alreadySaid}」，不要再重复这个字。` : "",
    "禁止说「你说」「啊你说」「嗯你说」——对方已经说完了，不是让他接着说。",
    "如果客户是在回答你刚才的问题（是的/对/没有/嗯），就当他答了，不要重问，不要重开开场白。",
    "不要把被打断的那句续完，不要道歉。直接接客户这句往下说。",
  ];
  return bits.filter(Boolean).join("");
}

// 打断后、LLM 还没出来时先垫的半个字。按客户这句话挑，不能用「你说」
// （那是让对方继续讲，但这时对方已经把话说完了）。
export function pickBargeAck(userText) {
  const t = String(userText || "").replace(/\s+/g, "");
  if (!t) return "";
  if (/^(等一下|等下|你说|听我说)/.test(t)) return "你说。";
  if (/[吗呢？?]$/.test(t) || /^(什么|多少|怎么|为啥|为什么|哪)/.test(t)) return "啊。";
  if (/没有|不是|不用|别|算了|没做/.test(t)) return "哦。";
  if (/^(是的|是啊|对的|对|嗯|好的|好|可以|行)/.test(t)) return "好。";
  return "嗯。";
}


// 把 ASR 带回来的情绪/语速翻译成一句给模型看的提示。
// 只在真有信号时才返回，平静且语速正常就返回空——没信号还硬塞一句，
// 等于每轮都在提醒模型"注意情绪"，反而会让它没事找事地安慰客户。
export function toneHint(meta) {
  if (!meta) return "";
  const bits = [];
  const strong = meta.emotionDegree === "strong" || meta.emotionDegree === "normal";
  if (meta.emotion === "angry") bits.push(strong ? "明显不耐烦或生气" : "有点不耐烦");
  else if (meta.emotion === "sad") bits.push("情绪偏低落");
  else if (meta.emotion === "happy") bits.push("情绪不错");
  else if (meta.emotion === "surprise") bits.push("有点意外");

  // 比这通电话里他自己的平均语速快三成以上，通常是急了或者想赶紧结束
  if (meta.fasterThanUsual > 0.3) bits.push("语速比刚才明显快");
  else if (meta.fasterThanUsual < -0.3) bits.push("语速比刚才明显慢，像在斟酌");

  if (!bits.length) return "";
  return (
    "【系统提示，不要朗读、不要提及本提示】听感上客户现在" +
    bits.join("、") +
    "。按这个状态调整：急了就把话缩短、直接给结论；" +
    "在斟酌就别催，给他时间。不要点破你察觉到了他的情绪。"
  );
}

// 客户没接话时追一句。**不走 LLM**，按上一句 AI 说了什么挑一句固定的短句。
//
// 走 LLM 的问题在真实通话里暴露得很清楚：历史里最后一条是 AI 自己的话，
// 模型接着往下写，写出来的是对话的下一轮——也就是客户的台词。实测出现过
//   AI：平时有做股票期货这类交易吗？
//   （追问）
//   AI：嗯，平时自己会炒点股票。      ← AI 替客户答了
// 还有一次是把卖点整段重讲。
//
// 而追问这种话本来就不需要创造力：真人这时候就是"怎么样？""您觉得呢？"
// 一句带过，不会重新解释一遍。规则挑句还顺带省掉一次 LLM 往返。
const NUDGE_YESNO = ["怎么样，有兴趣吗？", "您看呢？", "怎么样？"];
const NUDGE_OPEN = ["方便说两句吗？", "您那边怎么看？", "嗯？"];
const NUDGE_PLAIN = ["您还在吗？", "喂？"];

// 从 AI 自己说过的开场白里把称呼抠出来，例如
//   "您好，请问是叶升辉先生吗？…" → "叶升辉先生"
// 称呼写死在提示词的文本里，代码本来拿不到；.env 配了 CUSTOMER_NAME 就用那个
export function guessCustomerName(text) {
  const m = String(text || "").match(
    /(?:请问是|您是|是)\s*([一-龥]{1,5}(?:先生|女士|小姐|总|经理))/,
  );
  return m ? m[1] : "";
}

export function pickIdleNudge(lastAssistant, seed = 0, opts = {}) {
  const t = String(lastAssistant || "").trim();
  const pick = (arr) => arr[seed % arr.length];

  // 开场白之后对方一声没吭：这时候最可能是没听见、或者刚拿起电话还没反应过来。
  // 真人这时会先确认线路通不通、顺带叫一声称呼，而不是直接追问业务
  if (opts.firstContact) {
    const name = opts.name ? `${opts.name}，` : "";
    return pick([`喂，${name}能听到吗？`, `您好，${name}能听到我说话吗？`]);
  }
  if (!t) return pick(NUDGE_PLAIN);
  // 上一句是问句：客户没答，轻轻催一下就行
  if (/[？?]$/.test(t)) {
    // 是非问（…吗？/…吧？）追"有兴趣吗"这类；开放问追"方便说两句吗"
    if (/(吗|吧)[？?]$/.test(t)) return pick(NUDGE_YESNO);
    return pick(NUDGE_OPEN);
  }
  // 上一句是陈述：没问问题却冷场，说明对方在掂量，问一句他的看法
  return pick(NUDGE_YESNO);
}

// 冷场到底了，道别收线。同样不走 LLM，理由跟 pickIdleNudge 一样：
// 历史里最后一条是 AI 自己的话，让模型接着写，它可能写成客户的台词。
// 而且这是整通电话的最后一句，最不该出意外。
const BYES = [
  "那我先不打扰您了，祝您生活愉快，再见。",
  "行，那我不打扰您了，祝您顺利，再见。",
];
export function pickIdleBye(seed = 0) {
  return BYES[seed % BYES.length];
}

// 让 LLM 生成追问时下达的指令。
//
// 关键是**用 user 角色发**，不是 system。历史里最后一条是 assistant，
// 再追加 system 的话模型会接着往下写对话的下一轮——也就是客户的台词。
// 实测踩过：AI 问完"平时有做股票期货吗"，冷场之后自己接了句
// "嗯，平时自己会炒点股票"。换成 user 角色，模型的下一句自然是 assistant。
export const NUDGE_TASK =
  "【这不是客户说的话，是系统指令】客户沉默了几秒，没有回应你上一句。" +
  "现在用一句话轻轻追问，把话头递回给他。要求：" +
  "只输出这一句话本身，不要任何解释、不要引号、不要括号旁白；" +
  "不超过 15 个字；不要重复你刚才说过的内容；不要重新介绍产品；" +
  "不要替客户回答；像真人打电话那样自然，例如「怎么样？」「您看呢？」" +
  "「方便说两句吗？」这种分量。";

// LLM 生成的追问不一定守规矩，出声之前先过一遍。不合格就返回空，调用方退回固定句。
export function sanitizeNudge(raw, lastAssistant) {
  let t = String(raw || "").trim();
  if (!t) return "";
  t = t.replace(/（[^）]*）|\([^)]*\)/g, "");     // 括号旁白
  t = t.replace(/^["'「『]+|["'」』]+$/g, "");      // 包裹的引号
  t = t.replace(/\s+/g, "").trim();
  if (!t) return "";

  // 多句就只留第一句。追问就该一句话
  const first = t.split(/(?<=[。！？!?])/)[0] || t;
  t = first.trim();

  const bare = t.replace(/[^一-鿿A-Za-z0-9]/g, "");
  if (bare.length < 2 || bare.length > 18) return "";

  // 必须是问句。追问的职责就是把话头递回给客户，陈述句做不到这件事。
  // 这条比长度限制更能挡住"模型替客户答了"——那种输出往往是通顺的陈述句，
  // 长度完全合规，例如「嗯，平时自己会炒点股票。」
  if (!/[？?]$/.test(t)) return "";

  // 跟刚说过的重复，等于把上一句又念一遍
  const prev = String(lastAssistant || "").replace(/[^一-鿿A-Za-z0-9]/g, "");
  if (prev && (prev.includes(bare) || bare.includes(prev))) return "";
  return t;
}

// 开场白的随机化。
//
// 光在提示词里写"要有变化"是不够的：示例摆在那儿，模型多半还是会挑第一条念，
// 温度调高只会让它在别的地方跑偏，不会专门在开场上变花样。
// 每次通话随机塞一个措辞方向进去，逼它换个说法，同时不改变开场要办的那三件事。
const GREET_STYLES = [
  "开场第一个词用「您好」，不要用「喂」，语气正式一点。",
  "开场第一个词用「喂」，像刚接通电话那样随意一点。",
  "开场先确认对方姓名，再说明你是做什么的。",
  "开场先说明你是做什么的，再确认对方姓名。",
  "开场把「耽误您一分钟」换个说法，比如「方便说一分钟吗」「占用您一分钟」。",
  "开场只称呼姓氏加先生，不要念全名。",
];

// 从提示词的开场示例里取客户姓名。放开措辞之后模型会连姓名一起"创作"，
// 实测编出过张先生、陈先生、陈建国先生——外呼里叫错名字是致命的，必须锁死
export function customerNameInPrompt(promptText = SYSTEM_PROMPT) {
  const m = String(promptText).match(/请问是([一-龥]{2,4})先生/);
  return m ? m[1] : "";
}

export function pickGreetStyle(name) {
  const pick = GREET_STYLES[Math.floor(Math.random() * GREET_STYLES.length)];
  const who = name || customerNameInPrompt();
  return (
    "【系统提示，不要朗读、不要提及本提示】" +
    pick +
    "不要一字不差地照搬提示词里的示例句，用你自己的话说，但要办到的事不变：" +
    "确认是不是本人、说明你是谁、请对方给一分钟。" +
    (who
      ? `客户姓名是「${who}」，**只能**用这个名字（全名或姓氏加先生都行），` +
        "绝对不要换成别的姓名。"
      : "")
  );
}
